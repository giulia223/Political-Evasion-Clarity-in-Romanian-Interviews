"""EDA with tokenizers (T1.1). Writes docs/EDA.md.

python scripts/eda.py [--rows N]
Downloads only public tokenizers (no model weights).
"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from polero.data import ROOT, load_test, load_train, qa_key  # noqa: E402
from polero.text import normalize  # noqa: E402

TOKENIZERS = [
    "readerbench/RoBERT-large",
    "dumitrescustefan/bert-base-romanian-cased-v1",
    "FacebookAI/xlm-roberta-large",
]
COMMA, CEDILLA = "șțȘȚ", "şţŞŢ"


def vocab_diacritics(tok):
    v = tok.get_vocab()
    has = lambda chars: sum(any(c in t for c in chars) for t in v)  # noqa: E731
    return has(COMMA), has(CEDILLA)


def unk_and_fertility(tok, texts):
    ids = tok(list(texts), add_special_tokens=False)["input_ids"]
    n_tok = sum(len(i) for i in ids)
    n_words = sum(len(t.split()) for t in texts)
    unk = tok.unk_token_id
    n_unk = sum(sum(x == unk for x in i) for i in ids) if unk is not None else 0
    return n_unk / max(1, n_tok), n_tok / max(1, n_words), [len(i) for i in ids]


def tokenizer_section(name, tr, rows):
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(name)
    nc, nced = vocab_diacritics(tok)
    q = tr["interview_question"].tolist()[:rows]
    a = tr["interview_answer"].tolist()[:rows]
    texts = [x + " " + y for x, y in zip(q, a)]
    res = {"name": name, "fast": tok.is_fast, "vocab": len(tok), "vocab_comma": nc, "vocab_cedilla": nced,
           "lower": bool(getattr(tok, "do_lower_case", False) or tok.init_kwargs.get("do_lower_case", False))}
    for mode in ("basic", "comma", "cedilla"):
        u, f, _ = unk_and_fertility(tok, [normalize(t, mode) for t in texts])
        res[f"unk_{mode}"], res[f"fert_{mode}"] = u, f
    _, _, raw_len = unk_and_fertility(tok, texts)
    res["raw_unk"], res["raw_fert"] = unk_and_fertility(tok, texts)[:2]
    best = min(("basic", "comma", "cedilla"), key=lambda m: (res[f"unk_{m}"], res[f"fert_{m}"]))
    res["best_mode"] = best
    ql = [len(i) for i in tok([normalize(x, best) for x in q], add_special_tokens=False)["input_ids"]]
    al = [len(i) for i in tok([normalize(x, best) for x in a], add_special_tokens=False)["input_ids"]]
    qa = np.array(ql) + np.array(al) + 3
    res.update({
        "q_p50": int(np.median(ql)), "q_p95": int(np.percentile(ql, 95)), "q_max": int(max(ql)),
        "a_p50": int(np.median(al)), "a_p95": int(np.percentile(al, 95)), "a_max": int(max(al)),
        "qa_p50": int(np.median(qa)), "qa_p90": int(np.percentile(qa, 90)),
        "gt256": float((qa > 256).mean()), "gt512": float((qa > 512).mean()),
        "q_gt128": float((np.array(ql) > 128).mean()),
    })
    lab = tr["evasion_label"].iloc[:rows].to_numpy()
    res["per_label_gt512"] = {l: float((qa[lab == l] > 512).mean()) for l in np.unique(lab)}
    res["per_label_median"] = {l: int(np.median(qa[lab == l])) for l in np.unique(lab)}
    return res


def structure_section(tr, te):
    out = {}
    ktr, kte = set(qa_key(tr)), qa_key(te)
    out["test_exact_dup_in_train"] = int(kte.isin(ktr).sum())
    out["test_answer_in_train"] = int(te["interview_answer"].str.strip().isin(set(tr["interview_answer"].str.strip())).sum())
    out["train_dup_pairs"] = int(qa_key(tr).duplicated().sum())
    allr = pd.concat([tr.assign(split="train"), te.assign(split="test")])
    out["interviews"] = allr["url"].nunique()
    out["test_interviews_with_train"] = int(te["url"].isin(set(tr["url"])).sum())
    gaps = []
    for _, g in allr.sort_values("question_order").groupby("url"):
        o = g["question_order"].to_numpy()
        gaps += list(np.diff(o))
    out["gap_counts"] = pd.Series(gaps).value_counts().head(5).to_dict()
    # does a test row have a labeled neighbour (previous/next turn) in train?
    lab = set(zip(tr["url"], tr["question_order"]))
    out["test_with_labeled_neighbour"] = int(sum(((u, o - 1) in lab) or ((u, o + 1) in lab)
                                               for u, o in zip(te["url"], te["question_order"])))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=None)
    ap.add_argument("--out", default=str(ROOT / "docs" / "EDA.md"))
    a = ap.parse_args()
    tr, te = load_train(), load_test()
    rows = a.rows or len(tr)
    tok_res = [tokenizer_section(n, tr, rows) for n in TOKENIZERS]
    st = structure_section(tr, te)
    L = ["# EDA (T1.1)", "", f"Generated by `scripts/eda.py` on {rows} train rows. Token counts exclude special tokens unless noted.", ""]
    L += ["## Tokenizers and diacritics", "",
          "| tokenizer | fast | vocab | lowercases | vocab tokens with ș/ț (comma) | with ş/ţ (cedilla) | UNK raw | UNK comma | UNK cedilla | fertility raw | fertility comma | fertility cedilla | best mode |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in tok_res:
        L.append(f"| {r['name']} | {r['fast']} | {r['vocab']} | {r['lower']} | {r['vocab_comma']} | {r['vocab_cedilla']} | "
                 f"{r['raw_unk']:.4%} | {r['unk_comma']:.4%} | {r['unk_cedilla']:.4%} | {r['raw_fert']:.3f} | "
                 f"{r['fert_comma']:.3f} | {r['fert_cedilla']:.3f} | {r['best_mode']} |")
    L += ["", "## Lengths (tokens, under each tokenizer's best mode)", "",
          "| tokenizer | Q p50 | Q p95 | Q max | Q>128 | A p50 | A p95 | A max | Q+A p50 | Q+A p90 | Q+A>256 | Q+A>512 |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in tok_res:
        L.append(f"| {r['name']} | {r['q_p50']} | {r['q_p95']} | {r['q_max']} | {r['q_gt128']:.1%} | {r['a_p50']} | {r['a_p95']} | "
                 f"{r['a_max']} | {r['qa_p50']} | {r['qa_p90']} | {r['gt256']:.1%} | {r['gt512']:.1%} |")
    L += ["", "### Share of Q+A above 512 tokens per evasion label (first tokenizer)", "",
          "| label | median Q+A tokens | >512 |", "|---|---|---|"]
    r0 = tok_res[0]
    for l in r0["per_label_gt512"]:
        L.append(f"| {l} | {r0['per_label_median'][l]} | {r0['per_label_gt512'][l]:.1%} |")
    L += ["", "## Duplicates and interview structure", ""]
    for k, v in st.items():
        L.append(f"- {k}: {v}")
    L += ["", "## Label rates", "", "### Per president (row %)", "",
          (pd.crosstab(tr["president"], tr["evasion_label"], normalize="index") * 100).round(1).to_markdown()
          if _has_tabulate() else (pd.crosstab(tr["president"], tr["evasion_label"], normalize="index") * 100).round(1).to_string(),
          "", "### Per context (row %)", "",
          (pd.crosstab(tr["context"], tr["clarity_label"], normalize="index") * 100).round(1).to_markdown()
          if _has_tabulate() else (pd.crosstab(tr["context"], tr["clarity_label"], normalize="index") * 100).round(1).to_string(),
          ""]
    L += ["## Recommendations", ""]
    for r in tok_res:
        L.append(f"- `{r['name']}`: normalization mode `{r['best_mode']}`; {r['gt512']:.1%} of Q+A exceed 512 tokens.")
    L += ["- max_length 512, stride 128, question cap 128 tokens (question is >128 tokens in only a few % of rows).",
          "- max_chunks 8 keeps every answer token for all but the very longest answers."]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def _has_tabulate():
    try:
        import tabulate  # noqa: F401
        return True
    except ImportError:
        return False


if __name__ == "__main__":
    main()
